# 辅助函数
# ═══════════════════════════════════════════════════════════════

def format_context_from_chunks(chunks: list[dict]) -> str:
    """将精排后的文档块格式化为 RAG 上下文。

    Args:
        chunks: 重排后的文档列表，每条包含 parent_content、source_name、sku 等。

    Returns:
        格式化后的上下文字符串。
    """
    if not chunks:
        return "（暂无检索资料）"

    parts = []
    for i, chunk in enumerate(chunks):
        source = chunk.get("source_name", "未知来源")
        sku = chunk.get("sku", "")
        content = chunk.get("parent_content", chunk.get("child_content", ""))
        header = f"[资料{i + 1}] 来源: {source}"
        if sku:
            header += f" | SKU: {sku}"
        parts.append(f"{header}\n{content}")

    return "\n\n".join(parts)
